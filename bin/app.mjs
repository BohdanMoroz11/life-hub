#!/usr/bin/env node
// Manages the set of apps behind the hub. apps.json is the source of truth.
//   app add <repo> <subdomain> "<Name>" ["<description>"]   register an existing repo in ~/projects and start it
//   app caddy                                               regenerate the Caddy routes and reload
//   app docs                                                refresh the Deployment block in every app's AGENTS.md
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const HUB = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const PROJECTS = path.dirname(HUB);
const DOMAIN = "bohdanmoroz.com";
const APPS_FILE = path.join(HUB, "apps.json");
const CADDY_FILE = path.join(os.homedir(), "reverse-proxy/conf.d/apps.caddy");
const START = "<!-- platform:start -->";
const END = "<!-- platform:end -->";
const LIVE = 'concurrently -k -n web,api "vite build --watch" "tsx watch server/index.ts"';

const readApps = () => JSON.parse(fs.readFileSync(APPS_FILE, "utf8"));
const template = (name) => fs.readFileSync(path.join(HUB, "templates", name), "utf8");
const fill = (text, app) => text.replaceAll("{{repo}}", app.repo).replaceAll("{{subdomain}}", app.subdomain).replaceAll("{{domain}}", DOMAIN);
const caddyExec = (...args) => execFileSync("docker", ["exec", "caddy", "caddy", ...args, "--config", "/etc/caddy/Caddyfile"], { stdio: "pipe" });

function writeCaddy() {
  const blocks = readApps().map(
    (a) => `${a.subdomain}.${DOMAIN} {\n    encode gzip zstd\n    import hub_auth\n    reverse_proxy ${a.repo}:3000\n}\n`,
  );
  const text = `# Generated by hub/bin/app.mjs from hub/apps.json. Edit those, not this.
(hub_auth) {
    forward_auth hub:3000 {
        uri /auth
    }
}

apps.${DOMAIN} {
    encode gzip zstd
    reverse_proxy hub:3000
}

${blocks.join("\n")}`;
  const previous = fs.existsSync(CADDY_FILE) ? fs.readFileSync(CADDY_FILE, "utf8") : null;
  fs.writeFileSync(CADDY_FILE, text);
  try {
    caddyExec("validate");
    caddyExec("reload");
  } catch (err) {
    if (previous === null) fs.rmSync(CADDY_FILE);
    else fs.writeFileSync(CADDY_FILE, previous);
    console.error("Caddy rejected the new config, so the old one was restored.");
    throw err;
  }
}

function writeDocs(app) {
  const file = path.join(PROJECTS, app.repo, "AGENTS.md");
  const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  const note = app.agentNote ? `- ${app.agentNote}\n` : "";
  const block = `${START}\n${fill(template("agents-block.md"), app).trimEnd()}\n${note}${END}`;
  const a = existing.indexOf(START);
  const z = existing.indexOf(END);
  const next = a >= 0 && z > a ? existing.slice(0, a) + block + existing.slice(z + END.length) : `${existing.trimEnd()}\n\n${block}\n`.trimStart();
  fs.writeFileSync(file, next);
  if (!fs.existsSync(path.join(PROJECTS, app.repo, "CLAUDE.md"))) fs.writeFileSync(path.join(PROJECTS, app.repo, "CLAUDE.md"), "@AGENTS.md\n");
}

function add(repo, subdomain, name, description) {
  if (!repo || !subdomain || !name) throw new Error('Usage: app add <repo> <subdomain> "<Name>" ["<description>"]');
  const dir = path.join(PROJECTS, repo);
  if (!fs.existsSync(path.join(dir, "package.json"))) throw new Error(`${dir} has no package.json`);
  const apps = readApps();
  if (apps.some((a) => a.repo === repo || a.subdomain === subdomain)) throw new Error(`${repo} or ${subdomain} is already registered`);
  const app = { repo, subdomain, name, description };

  const compose = path.join(dir, "compose.yml");
  if (!fs.existsSync(compose)) fs.writeFileSync(compose, fill(template("compose.yml"), app));
  const pkgFile = path.join(dir, "package.json");
  const pkg = JSON.parse(fs.readFileSync(pkgFile, "utf8"));
  pkg.scripts ??= {};
  pkg.scripts.live ??= LIVE;
  fs.writeFileSync(pkgFile, JSON.stringify(pkg, null, 2) + "\n");

  fs.writeFileSync(APPS_FILE, JSON.stringify([...apps, app], null, 2) + "\n");
  writeDocs(app);
  execFileSync("docker", ["compose", "up", "-d"], { cwd: dir, stdio: "inherit" });
  writeCaddy();
  console.log(`Live at https://${subdomain}.${DOMAIN}`);
}

const [command, ...args] = process.argv.slice(2);
if (command === "add") add(...args);
else if (command === "caddy") writeCaddy();
else if (command === "docs") readApps().forEach(writeDocs);
else {
  console.error('Usage: app add <repo> <subdomain> "<Name>" ["<description>"] | app caddy | app docs');
  process.exit(1);
}
